#!/usr/bin/env node
/**
 * Migration DML extractor → one-off admin backfill jobs.
 *
 * Scans every file in supabase/migrations/ for top-level data-mutating
 * statements (INSERT / UPDATE / DELETE / TRUNCATE against public.*) and
 * generates an equivalent admin-gated one-off backfill job for each
 * migration that contains them, so future backfills never have to live
 * inside a migration (which trips the "conflicts with live data" publish
 * gate).
 *
 * Generated jobs land in supabase/backfills/<migration>.backfill.sql as a
 * SECURITY DEFINER function `public.admin_backfill_<slug>(_dry_run boolean)`:
 *   - checks has_role(auth.uid(),'admin') first
 *   - REVOKEs EXECUTE from PUBLIC, anon
 *   - supports a dry-run preview before applying
 *
 * Usage:
 *   node scripts/extract-migration-dml.mjs            # write job files
 *   node scripts/extract-migration-dml.mjs --list     # report only
 *   node scripts/extract-migration-dml.mjs --check    # exit 1 if any job file is missing/stale
 *
 * Statements inside function/DO bodies are runtime logic, not
 * migration-time backfills, and are ignored — same rule as
 * scripts/verify-migration-idempotency.mjs.
 */
import { readFileSync, readdirSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const MIGRATIONS_DIR = "supabase/migrations";
const OUT_DIR = "supabase/backfills";

const args = new Set(process.argv.slice(2));
const LIST_ONLY = args.has("--list");
const CHECK = args.has("--check");

const dmlRe =
  /^\s*(update|delete\s+from|insert\s+into|truncate)\s+(?:only\s+)?(public\.|"public"\.)/i;

/** Collect top-level DML statements (multi-line aware) from one migration. */
function collectDml(raw) {
  const lines = raw.split("\n");
  const found = [];
  let openTag = null;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const inBody = openTag !== null;
    for (const m of line.match(/\$[a-zA-Z_][a-zA-Z0-9_]*\$|\$\$/g) || []) {
      if (openTag === null) openTag = m;
      else if (openTag === m) openTag = null;
    }
    if (inBody) continue;
    if (!dmlRe.test(line)) continue;

    // Gather the full statement up to its terminating semicolon.
    const start = i;
    const buf = [];
    let j = i;
    for (; j < lines.length; j++) {
      buf.push(lines[j]);
      if (/;\s*(--.*)?$/.test(lines[j])) break;
    }
    i = j;

    found.push({
      line: start + 1,
      annotated: (lines[start - 1] || "").includes("idempotency-check: allow-dml"),
      sql: buf.join("\n").trim(),
    });
  }
  return found;
}

const slugify = (file) =>
  file
    .replace(/\.sql$/, "")
    .replace(/[^a-zA-Z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .slice(0, 48)
    .toLowerCase();

function renderJob(file, statements) {
  const fn = `admin_backfill_${slugify(file)}`;
  const body = statements
    .map(
      (s) =>
        `  -- from ${file}:${s.line}\n` +
        s.sql
          .split("\n")
          .map((l) => `  ${l}`)
          .join("\n"),
    )
    .join("\n\n");

  return `-- GENERATED by scripts/extract-migration-dml.mjs — do not edit by hand.
-- One-off admin backfill extracted from ${file}.
-- Run it from the admin dashboard (or as service_role) instead of shipping
-- the DML inside a migration.

CREATE OR REPLACE FUNCTION public.${fn}(_dry_run boolean DEFAULT true)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $fn$
DECLARE
  _affected bigint := 0;
  _rows bigint;
BEGIN
  IF NOT public.has_role(auth.uid(), 'admin') THEN
    RAISE EXCEPTION 'admin role required';
  END IF;

  IF _dry_run THEN
    RETURN jsonb_build_object(
      'dry_run', true,
      'source_migration', ${JSON.stringify(file).replace(/"/g, "'")},
      'statements', ${statements.length}
    );
  END IF;

${body}

  GET DIAGNOSTICS _rows = ROW_COUNT;
  _affected := _affected + _rows;

  RETURN jsonb_build_object('dry_run', false, 'rows_affected', _affected);
END;
$fn$;

REVOKE EXECUTE ON FUNCTION public.${fn}(boolean) FROM PUBLIC, anon;
GRANT  EXECUTE ON FUNCTION public.${fn}(boolean) TO authenticated, service_role;
`;
}

const files = readdirSync(MIGRATIONS_DIR)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const withDml = [];
for (const file of files) {
  const statements = collectDml(readFileSync(path.join(MIGRATIONS_DIR, file), "utf8"));
  if (statements.length) withDml.push({ file, statements });
}

if (!withDml.length) {
  console.log(`No migration DML found across ${files.length} migration file(s).`);
  process.exit(0);
}

let stale = 0;
if (!LIST_ONLY) mkdirSync(OUT_DIR, { recursive: true });

for (const { file, statements } of withDml) {
  const out = path.join(OUT_DIR, `${file.replace(/\.sql$/, "")}.backfill.sql`);
  const content = renderJob(file, statements);
  const unannotated = statements.filter((s) => !s.annotated).length;

  console.log(
    `${file}: ${statements.length} DML statement(s)` +
      (unannotated ? `, ${unannotated} missing allow-dml annotation` : "") +
      (LIST_ONLY ? "" : ` → ${out}`),
  );

  if (LIST_ONLY) continue;

  const current = existsSync(out) ? readFileSync(out, "utf8") : null;
  if (current !== content) {
    stale++;
    if (!CHECK) writeFileSync(out, content);
  }
}

if (CHECK && stale) {
  console.error(
    `\n${stale} backfill job file(s) are missing or out of date. ` +
      `Run: node scripts/extract-migration-dml.mjs`,
  );
  process.exit(1);
}

console.log(
  `\n${withDml.length} migration(s) with DML; ` +
    (LIST_ONLY ? "listed only." : `${stale} job file(s) written to ${OUT_DIR}/.`),
);
